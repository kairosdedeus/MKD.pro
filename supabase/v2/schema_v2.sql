alter table public."Usuario" enable row level security;
alter table public."Equipe" enable row level security;
alter table public."Funcao" enable row level security;
alter table public."EquipeMembro" enable row level security;
alter table public."EquipeMembroFuncao" enable row level security;
alter table public."Escala" enable row level security;
alter table public."EscalaMembro" enable row level security;
alter table public."EscalaMembroFuncao" enable row level security;
alter table public."Musica" enable row level security;
alter table public."EscalaMusica" enable row level security;
alter table public."EquipePadrao" enable row level security;
alter table public."EquipePadraoMembro" enable row level security;
alter table public."Presenca" enable row level security;
alter table public."Notificacao" enable row level security;
alter table public."NotificacaoDestinatario" enable row level security;
alter table public."ConteudoSite" enable row level security;

create policy "Usuario_Ler_Proprio_Ou_Gerencial"
on public."Usuario"
for select to authenticated
using (
  "Id" = (select public."UsuarioAtualId"())
  or (select public."EhGerencial"())
);

create policy "Equipe_Ler_Se_Participa"
on public."Equipe"
for select to authenticated
using ((select public."ParticipaDaEquipe"("Id")));

create policy "Funcao_Ler_Autenticado"
on public."Funcao"
for select to authenticated
using (true);

create policy "EquipeMembro_Ler_Equipe"
on public."EquipeMembro"
for select to authenticated
using ((select public."ParticipaDaEquipe"("EquipeId")));

create policy "EquipeMembroFuncao_Ler_Equipe"
on public."EquipeMembroFuncao"
for select to authenticated
using (
  exists (
    select 1
    from public."EquipeMembro" em
    where em."Id" = "EquipeMembroFuncao"."EquipeMembroId"
      and public."ParticipaDaEquipe"(em."EquipeId")
  )
);

create policy "Escala_Ler_Equipe"
on public."Escala"
for select to authenticated
using ((select public."ParticipaDaEquipe"("EquipeId")));

create policy "Escala_Criar_Equipe"
on public."Escala"
for insert to authenticated
with check ((select public."PodeGerenciarEquipe"("EquipeId")));

create policy "Escala_Atualizar_Equipe"
on public."Escala"
for update to authenticated
using ((select public."PodeGerenciarEquipe"("EquipeId")))
with check ((select public."PodeGerenciarEquipe"("EquipeId")));

create policy "Escala_Excluir_Gerencial"
on public."Escala"
for delete to authenticated
using ((select public."EhGerencial"()));

create policy "Musica_Ler_Louvor"
on public."Musica"
for select to authenticated
using (
  (select public."EhGerencial"())
  or exists (
    select 1
    from public."EquipeMembro" em
    join public."Equipe" e on e."Id" = em."EquipeId"
    where em."UsuarioId" = public."UsuarioAtualId"()
      and em."Ativo" = true
      and e."Ativo" = true
      and e."Ministerio" = 'Louvor'
  )
);

create policy "NotificacaoDestinatario_Ler_Propria"
on public."NotificacaoDestinatario"
for select to authenticated
using ("UsuarioId" = (select public."UsuarioAtualId"()));

create policy "NotificacaoDestinatario_Atualizar_Propria"
on public."NotificacaoDestinatario"
for update to authenticated
using ("UsuarioId" = (select public."UsuarioAtualId"()))
with check ("UsuarioId" = (select public."UsuarioAtualId"()));

create policy "ConteudoSite_Ler_Publicado"
on public."ConteudoSite"
for select to anon, authenticated
using ("Publicado" = true or auth.uid() is not null);

