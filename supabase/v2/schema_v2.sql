create or replace function public."ValidarFuncaoDoMembro"()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  "MinisterioDaEquipe" public."Ministerio";
  "MinisterioDaFuncao" public."Ministerio";
begin
  select e."Ministerio"
    into "MinisterioDaEquipe"
  from public."EquipeMembro" em
  join public."Equipe" e on e."Id" = em."EquipeId"
  where em."Id" = new."EquipeMembroId";

  select f."Ministerio"
    into "MinisterioDaFuncao"
  from public."Funcao" f
  where f."Id" = new."FuncaoId";

  if "MinisterioDaEquipe" is distinct from "MinisterioDaFuncao" then
    raise exception 'A função não pertence ao ministério da equipe.';
  end if;

  return new;
end;
$$;

create trigger "TR_EquipeMembroFuncao_ValidarMinisterio"
before insert or update on public."EquipeMembroFuncao"
for each row execute function public."ValidarFuncaoDoMembro"();

create or replace function public."ValidarMembroDaEscala"()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  "EquipeDaEscalaId" integer;
  "EquipeDoMembroId" integer;
begin
  select "EquipeId"
    into "EquipeDaEscalaId"
  from public."Escala"
  where "Id" = new."EscalaId";

  select "EquipeId"
    into "EquipeDoMembroId"
  from public."EquipeMembro"
  where "Id" = new."EquipeMembroId"
    and "Ativo" = true;

  if "EquipeDaEscalaId" is distinct from "EquipeDoMembroId" then
    raise exception 'O membro não pertence à equipe desta escala.';
  end if;

  return new;
end;
$$;

create trigger "TR_EscalaMembro_ValidarEquipe"
before insert or update on public."EscalaMembro"
for each row execute function public."ValidarMembroDaEscala"();

create or replace function public."ValidarFuncaoDaEscala"()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  "MinisterioDaEscala" public."Ministerio";
  "MinisterioDaFuncao" public."Ministerio";
begin
  select e."Ministerio"
    into "MinisterioDaEscala"
  from public."EscalaMembro" esm
  join public."Escala" es on es."Id" = esm."EscalaId"
  join public."Equipe" e on e."Id" = es."EquipeId"
  where esm."Id" = new."EscalaMembroId";

  select "Ministerio"
    into "MinisterioDaFuncao"
  from public."Funcao"
  where "Id" = new."FuncaoId";

  if "MinisterioDaEscala" is distinct from "MinisterioDaFuncao" then
    raise exception 'A função não pertence ao ministério desta escala.';
  end if;

  return new;
end;
$$;

create trigger "TR_EscalaMembroFuncao_ValidarMinisterio"
before insert or update on public."EscalaMembroFuncao"
for each row execute function public."ValidarFuncaoDaEscala"();

create or replace function public."ValidarEquipePadrao"()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public."Equipe"
    where "Id" = new."EquipeId"
      and "Ministerio" = 'Louvor'
  ) then
    raise exception 'Equipe padrão somente pode pertencer ao ministério de Louvor.';
  end if;

  return new;
end;
$$;

create trigger "TR_EquipePadrao_ValidarLouvor"
before insert or update on public."EquipePadrao"
for each row execute function public."ValidarEquipePadrao"();

create or replace function public."ValidarMembroDaEquipePadrao"()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  "EquipePadraoEquipeId" integer;
  "MembroEquipeId" integer;
  "FuncaoMinisterio" public."Ministerio";
begin
  select "EquipeId"
    into "EquipePadraoEquipeId"
  from public."EquipePadrao"
  where "Id" = new."EquipePadraoId";

  select "EquipeId"
    into "MembroEquipeId"
  from public."EquipeMembro"
  where "Id" = new."EquipeMembroId"
    and "Ativo" = true;

  select "Ministerio"
    into "FuncaoMinisterio"
  from public."Funcao"
  where "Id" = new."FuncaoId";

  if "EquipePadraoEquipeId" is distinct from "MembroEquipeId" then
    raise exception 'O membro não pertence à equipe deste padrão.';
  end if;

  if "FuncaoMinisterio" is distinct from 'Louvor'::public."Ministerio" then
    raise exception 'A função da equipe padrão precisa ser do Louvor.';
  end if;

  return new;
end;
$$;

