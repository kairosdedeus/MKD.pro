-- =============================================================================
-- MKD V2 - MODELO DE DADOS SIMPLIFICADO
-- =============================================================================
-- IMPORTANTE:
-- 1. Execute somente em um projeto Supabase novo e vazio.
-- 2. Todos os identificadores PascalCase precisam permanecer entre aspas.
-- 3. IDs do domínio são integer; somente o vínculo com auth.users usa UUID.
-- =============================================================================

begin;

create extension if not exists citext;

-- =============================================================================
-- TIPOS DO DOMÍNIO
-- =============================================================================

create type public."Ministerio" as enum (
  'Louvor',
  'Danca',
  'Midia',
  'Obreiros',
  'Celula'
);

create type public."PapelEquipe" as enum (
  'Lider',
  'Auxiliar',
  'Membro'
);

create type public."StatusEscala" as enum (
  'Rascunho',
  'Publicada',
  'Concluida',
  'Cancelada'
);

create type public."StatusConfirmacao" as enum (
  'Pendente',
  'Confirmada',
  'Recusada'
);

create type public."TipoNotificacao" as enum (
  'EscalaCriada',
  'EscalaAtualizada',
  'EscalaPublicada',
  'EscalaExcluida',
  'PessoaEscalada',
  'Informacao'
);

-- =============================================================================
-- 1. USUÁRIOS
-- Substitui users_profile, profiles e user_profiles.
-- Acesso gerencial é explícito. Acesso ministerial é derivado de EquipeMembro.
-- =============================================================================

create table public."Usuario" (
  "Id" integer generated by default as identity primary key,
  "AuthId" uuid unique references auth.users(id) on delete cascade,
  "Nome" varchar(100) not null,
  "Sobrenome" varchar(150),
  "Email" citext not null unique,
  "Telefone" varchar(20),
  "Gerencial" boolean not null default false,
  "Ativo" boolean not null default true,
  "CriadoEm" timestamptz not null default now(),
  "AtualizadoEm" timestamptz not null default now(),
  constraint "CK_Usuario_Nome" check (length(trim("Nome")) >= 2),
  constraint "CK_Usuario_Email" check (position('@' in "Email"::text) > 1)
);

comment on table public."Usuario" is
  'Cadastro da pessoa no MKD. AuthId é o único UUID do domínio por integrar com Supabase Auth.';

-- =============================================================================
-- 2. EQUIPES
-- Também representa Células. Campos de encontro ficam preenchidos em Celula.
-- ConfiguracaoRodizio guarda somente regras variáveis e validadas do Louvor.
-- =============================================================================

create table public."Equipe" (
  "Id" integer generated by default as identity primary key,
  "Nome" varchar(120) not null,
  "Ministerio" public."Ministerio" not null,
  "Cor" varchar(20),
  "LocalEncontro" varchar(200),
  "DiaSemana" smallint,
  "HorarioEncontro" time,
  "Observacoes" text,
  "ConfiguracaoRodizio" jsonb not null default '{}'::jsonb,
  "Ativo" boolean not null default true,
  "CriadoEm" timestamptz not null default now(),
  "AtualizadoEm" timestamptz not null default now(),
  constraint "CK_Equipe_Nome" check (length(trim("Nome")) >= 2),
  constraint "CK_Equipe_DiaSemana" check (
    "DiaSemana" is null or "DiaSemana" between 0 and 6
  ),
  constraint "CK_Equipe_ConfiguracaoRodizio" check (
    jsonb_typeof("ConfiguracaoRodizio") = 'object'
  )
);

create unique index "UX_Equipe_Ministerio_Nome_Ativa"
  on public."Equipe" ("Ministerio", lower("Nome"))
  where "Ativo" = true;

comment on column public."Equipe"."DiaSemana" is
  '0=domingo, 1=segunda, 2=terça, 3=quarta, 4=quinta, 5=sexta, 6=sábado.';

comment on column public."Equipe"."ConfiguracaoRodizio" is
  'Configuração variável do rodízio. Não usar para dados relacionais ou campos comuns.';

