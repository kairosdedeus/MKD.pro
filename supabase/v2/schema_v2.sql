create or replace function public."UsuarioAtualId"()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select "Id"
  from public."Usuario"
  where "AuthId" = auth.uid()
    and "Ativo" = true
  limit 1;
$$;

create or replace function public."EhGerencial"()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select "Gerencial"
    from public."Usuario"
    where "AuthId" = auth.uid()
      and "Ativo" = true
    limit 1
  ), false);
$$;

create or replace function public."ParticipaDaEquipe"("EquipeConsultadaId" integer)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public."EhGerencial"() or exists (
    select 1
    from public."EquipeMembro"
    where "EquipeId" = "EquipeConsultadaId"
      and "UsuarioId" = public."UsuarioAtualId"()
      and "Ativo" = true
  );
$$;

create or replace function public."PodeGerenciarEquipe"("EquipeConsultadaId" integer)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public."EhGerencial"() or exists (
    select 1
    from public."EquipeMembro"
    where "EquipeId" = "EquipeConsultadaId"
      and "UsuarioId" = public."UsuarioAtualId"()
      and "Papel" in ('Lider', 'Auxiliar')
      and "Ativo" = true
  );
$$;

revoke all on function public."UsuarioAtualId"() from public;
revoke all on function public."EhGerencial"() from public;
revoke all on function public."ParticipaDaEquipe"(integer) from public;
revoke all on function public."PodeGerenciarEquipe"(integer) from public;

grant execute on function public."UsuarioAtualId"() to authenticated;
grant execute on function public."EhGerencial"() to authenticated;
grant execute on function public."ParticipaDaEquipe"(integer) to authenticated;
grant execute on function public."PodeGerenciarEquipe"(integer) to authenticated;

-- =============================================================================
